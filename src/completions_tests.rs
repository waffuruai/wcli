use crate::{Arg, Command, Exit, Opt, Shell};

fn program() -> Command {
    Command::new("tool")
        .version("1.2.3")
        .option("-q, --quiet", "say less")
        .command(
            Command::new("report")
                .description("show the latest report. It never scans.")
                .arg(Arg::new("[part]", "what it covers").choices(&["findings", "summary"]))
                .option("-o, --out <file>", "write it there")
                .opt(Opt::new("-f, --format <kind>", "how").choices(&["table", "csv"]))
                .opt(Opt::new("--secret", "hidden").hide()),
        )
        .command(
            Command::new("schedule").subcommand_required().command(
                Command::new("install").opt(Opt::new("--every <period>", "how often").choices(&["day", "week"])),
            ),
        )
        .command(Command::new("export").alias("ex").description("it's quoted"))
        .command(Command::new("internal").hide())
        .completions()
}

fn script(shell: Shell) -> String {
    match program().parse(&["completions", shell.name()]) {
        Err(Exit::Help(s)) => s,
        other => panic!("{other:?}"),
    }
}

#[test]
fn the_completions_command_is_built_in() {
    let help = program().help_for(&[]).unwrap();
    assert!(help.contains("  completions <shell>"), "{help}");
    assert!(program().help_for(&["completions"]).unwrap().contains("choices: bash, zsh, fish"));
    match program().parse(&["completions"]) {
        Err(Exit::Error(t)) => assert!(t.contains("missing required argument 'shell'"), "{t}"),
        other => panic!("{other:?}"),
    }
    match program().parse(&["completions", "ksh"]) {
        Err(Exit::Error(t)) => assert!(t.contains("Allowed choices are bash, zsh, fish"), "{t}"),
        other => panic!("{other:?}"),
    }
    assert_eq!("fish".parse::<Shell>(), Ok(Shell::Fish));
    assert!("ksh".parse::<Shell>().is_err());
    assert_eq!(program().completion_script(Shell::Bash), script(Shell::Bash));
}

#[test]
fn bash_descends_the_tree_and_completes_words_and_values() {
    let s = script(Shell::Bash);
    assert!(s.starts_with("# bash completion for tool, generated by wcli"), "{s}");
    assert!(s.contains("'tool export'|'tool ex') path=\"$path export\" ;;"), "aliases descend to the real name\n{s}");
    assert!(s.contains("'tool schedule install') path=\"$path install\" ;;"), "{s}");
    assert!(
        s.contains(
            "'tool report -f'|'tool report --format') COMPREPLY=($(compgen -W 'table csv' -- \"$cur\")); return ;;"
        ),
        "{s}"
    );
    assert!(
        s.contains("'tool report -o'|'tool report --out') COMPREPLY=($(compgen -f -- \"$cur\")); return ;;"),
        "files for a value without choices\n{s}"
    );
    assert!(s.contains("'tool') COMPREPLY=($(compgen -W 'report schedule export ex completions help -q --quiet -h --help -V --version' -- \"$cur\")) ;;"), "{s}");
    assert!(s.contains("'tool report') COMPREPLY=($(compgen -W 'findings summary -o --out -f --format -q --quiet -h --help' -- \"$cur\")) ;;"), "argument choices, own options, then the parents'\n{s}");
    assert!(!s.contains("internal") && !s.contains("--secret"), "hidden things stay hidden\n{s}");
    assert!(s.ends_with("complete -F _tool tool\n"), "{s}");
}

#[test]
fn zsh_mirrors_bash_with_compadd() {
    let s = script(Shell::Zsh);
    assert!(s.starts_with("#compdef tool\n"), "{s}");
    assert!(s.contains("'tool schedule install --every') compadd -- 'day' 'week'; return ;;"), "{s}");
    assert!(s.contains("'tool report -o'|'tool report --out') _files; return ;;"), "{s}");
    assert!(s.contains("'tool schedule') compadd -- 'install' 'help' '-q' '--quiet' '-h' '--help' ;;"), "{s}");
    assert!(s.contains("compdef _tool tool"), "{s}");
}

#[test]
fn fish_uses_conditions_per_command() {
    let s = script(Shell::Fish);
    assert!(s.starts_with("# fish completion for tool, generated by wcli"), "{s}");
    assert!(s.contains("complete -c tool -f\n"), "{s}");
    assert!(s.contains("complete -c tool -n '__fish_use_subcommand' -a 'report' -d 'show the latest report'\n"), "{s}");
    assert!(
        s.contains("complete -c tool -n '__fish_use_subcommand' -a 'export ex' -d 'it'\\''s quoted'\n"),
        "quotes escaped\n{s}"
    );
    assert!(s.contains("complete -c tool -s q -l quiet -d 'say less'\n"), "root options need no condition\n{s}");
    assert!(
        s.contains(
            "complete -c tool -n '__fish_seen_subcommand_from report' -s f -l format -x -a 'table csv' -d 'how'\n"
        ),
        "{s}"
    );
    assert!(
        s.contains("complete -c tool -n '__fish_seen_subcommand_from report' -s o -l out -r -F -d 'write it there'\n"),
        "{s}"
    );
    assert!(s.contains("complete -c tool -n '__fish_seen_subcommand_from report' -a 'findings summary'\n"), "{s}");
    assert!(s.contains("complete -c tool -n '__fish_seen_subcommand_from schedule; and not __fish_seen_subcommand_from install' -a 'install'"), "{s}");
    assert!(s.contains("complete -c tool -n '__fish_seen_subcommand_from schedule; and __fish_seen_subcommand_from install' -l every -x -a 'day week'"), "{s}");
    assert!(!s.contains("internal") && !s.contains("secret"), "{s}");
}
